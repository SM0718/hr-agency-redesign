export function getInsightBySlug(slug: string): InsightPost | undefined {
  return insights.find((post) => post.slug === slug)
}

export function getRelatedInsights(current: InsightPost, count = 3): InsightPost[] {
  const linked = current.related
    .map((slug) => getInsightBySlug(slug))
    .filter((post): post is InsightPost => Boolean(post))
    .slice(0, count)
  if (linked.length >= count) return linked
  const rest = insights
    .filter((post) => post.slug !== current.slug && !linked.includes(post))
    .slice(0, count - linked.length)
  return [...linked, ...rest]
}